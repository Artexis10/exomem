@pytest.mark.parametrize("native_state", ("mismatch", "foreign"))
def test_pending_takeover_revokes_stale_rights_without_closing_displaced_copies(store, monkeypatch, tmp_path, native_state):
    birth = store.allocate_birth()
    owner, scope, before, original, path, _ = current_slot(store)
    old_ref = store.image_page(before.image_id, 0).value.fragments[0].source_ref
    abandoned_image = ready(store, reference())
    abandoned = store.reserve_copy(abandoned_image, owner=owner.model_copy(update={"version": uuid.uuid4().hex}),
                                   origin_ledger=scope, expected_header=store.image_header(abandoned_image).value,
                                   expected_root=store.root)
    stale = store.prepare_slot(owner=owner.owner, locator=owner.locator, physical_scope=scope,
                               expected_revision=original.slot.revision, expected_current_copy_id=before.copy_id,
                               candidate=abandoned, publication_id=uuid.uuid4().hex)
    publish_native(store, path, b"externally replaced generated bytes")
    result = store.settle_slot(stale, witness=lambda binding: native_proof(binding, scope, native_state))
    assert result.slot.pending is not None
    observed_epoch = store.head().epoch
    store.settle_slot(stale, witness=lambda binding: native_proof(binding, scope, native_state))
    assert store.head().epoch == observed_epoch
    monkeypatch.setenv("EXOMEM_STATE_ROOT", str(tmp_path / "takeover-cache"))
    replica = generated.GeneratedFragmentStore(store.root)
    fresh_image = ready(replica, reference(), horizon=observed_epoch)
    fresh = replica.reserve_copy(fresh_image, owner=owner.model_copy(update={"version": uuid.uuid4().hex}),
                                origin_ledger=scope, expected_header=replica.image_header(fresh_image).value,
                                expected_root=replica.root)
    with pytest.raises(ValueError, match="superseded"):
        replica.takeover_slot(replace(stale, physical_scope="another-physical-scope"),
                              candidate=fresh, publication_id=uuid.uuid4().hex)
    with pytest.raises(ValueError, match="fresh"):
        replica.takeover_slot(stale, candidate=abandoned, publication_id=uuid.uuid4().hex)
    fresh_right = replica.takeover_slot(stale, candidate=fresh, publication_id=uuid.uuid4().hex)
    pending = replica.check_slot(fresh_right)
    assert pending.current.copy_id == before.copy_id and pending.candidate == fresh
    assert pending.unknown_through_epoch >= observed_epoch
    for _delayed_callback in ("forward", "inverse"):
        with pytest.raises(ValueError, match="superseded"):
            replica.check_slot(stale)
    publish_native(replica, path, b"Exact generated bytes")
    installed = replica.settle_slot(fresh_right, witness=lambda binding: native_proof(binding, scope, "candidate"))
    assert installed.current == fresh and installed.slot.pending is None
    horizon = installed.unknown_through_epoch
    for _ in range(60):
        if replica.census(limit=8).state == "ready":
            break
    found = replica.lookup(old_ref, birth)
    assert found.state == "unknown" and before.copy_id in {copy.copy_id for copy in found.copies}
    with replica._connect() as conn:
        for copy in (before, abandoned, fresh):
            retained = generated.Copy.model_validate_json(conn.execute(
                "SELECT data FROM copies WHERE copy_id=?", (copy.copy_id,)).fetchone()[0])
            assert retained == copy
    later = replica.allocate_birth()
    assert replica.lookup(reference(), later).state == "ready"
    assert replica.read_slot(owner=owner.owner, locator=owner.locator, physical_scope=scope).unknown_through_epoch == horizon
    replica.close()


