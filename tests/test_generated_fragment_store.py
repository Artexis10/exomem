def test_page_budget_chain_and_building_copy_refusal(store):
    ref = reference()
    data = b"x" * 2400
    digest = hashlib.sha256(data).hexdigest()
    mapping = FragmentMap(image_sha256=digest, fragments=tuple(Fragment(
        opaque_fragment_id=f"{'λ' * 60}{n}", source_ref=ref, start_byte=n,
        end_byte=n + 1, payload_sha256=hashlib.sha256(b"x").hexdigest(),
    ) for n in range(len(data))))
    build = store.begin_image(data, mapping, unknown_through_epoch=0)
    assert len(build.pages) > 1
    owner = OwnerLocator(owner="native-stage", locator=uuid.uuid4().hex, version=uuid.uuid4().hex)
    with pytest.raises(ValueError, match="ready"):
        store.reserve_copy(build.header.image_id, owner=owner, origin_ledger=uuid.uuid4().hex,
                           expected_header=build.header, expected_root=store.root)
    for page in build.pages:
        assert len(generated.encode(page)) <= generated.MAX_RECORD_BYTES
        store.append_image(page)
    sealed = store.seal_image(build.header.image_id)
    assert sealed.last_page_hash == build.pages[-1].digest()
    assert store.image_page(sealed.image_id, 0).state == "observed"


def test_orphan_descriptor_consumes_epoch_without_replaying_image(store, monkeypatch):
    before = store.head().epoch
    original = vault_module.batch_atomic_write

    def fail_before_head(writes, **kwargs):
        writes = tuple(writes)
        if any(str(write.path).endswith("/head.json") for write in writes):
            raise RuntimeError("process lost before head install")
        return original(writes, **kwargs)

    with monkeypatch.context() as crashing:
        crashing.setattr(vault_module, "batch_atomic_write", fail_before_head)
