    store.reconcile()
    assert store.head().epoch == before + 1
    descriptor = json.loads((generated.canonical_root(store.root) / f"changes/{before + 1}.json").read_bytes())
    assert descriptor["operation"] == "no_effect" and descriptor["objects"] == []


