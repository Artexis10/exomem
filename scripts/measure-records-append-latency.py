def _parent(args: argparse.Namespace) -> int:
    results = []
    for size in [int(part) for part in args.sizes.split(",")]:
        print(f"== size {size} ==", file=sys.stderr, flush=True)
        # A briefly held file (a virus scanner on Windows) must not discard a finished measurement.
        with tempfile.TemporaryDirectory(prefix="exomem-append-latency-", ignore_cleanup_errors=True) as work_dir:
            completed = subprocess.run(
                [
                    sys.executable,
                    __file__,
                    "--child",
                    "--work-dir",
                    work_dir,
                    "--size",
                    str(size),
                    "--appends",
                    str(args.appends),
                    "--storage",
                    args.storage,
                    *(["--lift-caps"] if args.lift_caps else []),
                    *(["--phase-probes"] if args.phase_probes else []),
                ],
                capture_output=True,
                text=True,
                check=False,
            )
        # A failed child prints its whole log: a CI-only failure cannot be rerun locally.
        sys.stderr.write(completed.stderr if completed.returncode else completed.stderr[-2000:])
        if completed.returncode != 0:
            print(completed.stdout[-2000:], file=sys.stderr)
            return completed.returncode
        marker = "RESULT-JSON:"
        line = next(
            row for row in reversed(completed.stdout.splitlines()) if row.startswith(marker)
        )
        results.append(json.loads(line[len(marker) :]))
        text = json.dumps(results, indent=2).replace(f"{REPO}/", "")
        Path(args.out).write_text(text + "\n", encoding="utf-8")
    print(f"wrote {args.out}", file=sys.stderr)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", default="10,100,1000")
    parser.add_argument("--appends", type=int, default=30)
    parser.add_argument("--out", default="records-append-latency.json")
    parser.add_argument("--storage", choices=("files", "store"), default="files")
    parser.add_argument("--phase-probes", action="store_true",
                        help="add store-only 10%% ref-withheld and bulk-500 diagnostics")
    parser.add_argument(
        "--lift-caps",
        action="store_true",
        help="lift the 2,000-item collection caps (measurement of larger collections only)",
    )
    parser.add_argument("--child", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--size", type=int, default=0, help=argparse.SUPPRESS)
    parser.add_argument("--work-dir", help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.phase_probes and (args.storage != "store" or any(
        size < 10 or size % 10 for size in ([args.size] if args.child else map(int, args.sizes.split(",")))
    )):
        parser.error("--phase-probes requires --storage store and sizes divisible by 10 (at least 10)")
    if args.child:
        print("RESULT-JSON:" + json.dumps(_child(args)))
        return 0
    return _parent(args)


if __name__ == "__main__":
    raise SystemExit(main())
